import { test, expect } from '@playwright/test';

test('tabs preserve separate files and filters, including export', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('checkbox', { name: 'Debug total', exact: true }).check();
  const upload = async (name: string, text: string) => {
    await page.getByLabel('Ficheiro de logs', { exact: true }).setInputFiles({ name, mimeType: 'text/plain', buffer: Buffer.from(text) });
    await expect(page.locator('.header-file')).toHaveText(name);
  };
  await upload('ComServer.log', '2026/11/03 13:31:29.000|INFO|[1]|Example - original\n');
  await page.getByRole('button', { name: 'PollingV6', exact: true }).click();
  await expect(page.getByRole('checkbox', { name: 'Debug total', exact: true })).toHaveCount(0);
  const debug = '2026-11-03 13:31:29.9999|0|[12]|DEBUG|PollingV6Bridge.Hub|Starting Pay with request {}\r\n';
  const info = '2026-11-03 13:31:30.0000|0|[18]|INFO|PollingV6Bridge.Listener|Socket disconnected\r\n';
  await upload('PollingV6.log', debug + info);
  await expect(page.locator('.event-summary')).toHaveCount(2);
  await expect(page.locator('.polling-quick-button')).toHaveCount(6);
  const textSearch = page.getByRole('searchbox', { name: 'Buscar texto no log' });
  await page.keyboard.press('Control+f');
  await expect(textSearch).toBeFocused();
  await textSearch.fill('STARTING pay');
  await expect(page.locator('.event-summary')).toHaveCount(1);
  await page.getByRole('button', { name: 'Somente requests', exact: true }).click();
  await expect(textSearch).toHaveValue('STARTING pay');
  await expect(page.locator('.event-summary')).toHaveCount(1);
  await textSearch.fill('no match');
  await expect(page.locator('.event-summary')).toHaveCount(0);
  await page.getByRole('button', { name: 'Limpar filtros', exact: true }).click();
  await expect(textSearch).toHaveValue('');
  await expect(page.locator('.event-summary')).toHaveCount(2);
  await page.getByRole('button', { name: 'Erros de comunicação', exact: true }).click();
  await expect(page.locator('.event-summary')).toHaveCount(1);
  await page.getByRole('button', { name: 'Somente requests', exact: true }).click();
  await expect(page.locator('.polling-quick-button[aria-pressed="true"]')).toHaveCount(2);
  await expect(page.locator('.event-summary')).toHaveCount(0);
  await page.getByRole('button', { name: 'Erros de comunicação', exact: true }).click();
  await expect(page.locator('.event-summary')).toHaveCount(1);
  await expect(page.locator('.event-summary')).toContainText('Starting Pay');
  await page.getByRole('button', { name: 'Somente requests', exact: true }).click();
  await expect(page.locator('.event-summary')).toHaveCount(2);
  await page.getByRole('button', { name: 'Erros de comunicação', exact: true }).click();
  await expect(page.locator('.event-summary')).toHaveCount(1);
  await page.getByRole('button', { name: 'ComServer', exact: true }).click();
  await expect(page.locator('.header-file')).toHaveText('ComServer.log');
  await expect(page.getByRole('checkbox', { name: 'Debug total', exact: true })).toBeChecked();
  await expect(page.locator('.event-summary')).toHaveCount(1);
  await page.getByRole('button', { name: 'PollingV6', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Erros de comunicação', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('.event-summary')).toHaveCount(1);
  await page.getByRole('button', { name: 'Copiar resultados', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Resultados copiados');
  expect((await page.evaluate(() => navigator.clipboard.readText())).replaceAll('\r\n', '\n')).toBe(info.replaceAll('\r\n', '\n'));
  await page.getByRole('button', { name: 'Limpar filtros', exact: true }).click();
  await expect(page.locator('.polling-quick-button[aria-pressed="true"]')).toHaveCount(0);
  await expect(page.locator('.event-summary')).toHaveCount(2);
});
